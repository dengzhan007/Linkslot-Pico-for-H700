#!/usr/bin/env python3
"""Cross-check the M1 0x46200 runtime firmware stream against pinned BaseOS source and captured TOC1 metadata.

This is a source-contract and layout-arithmetic test. It does not read a device,
build a capsule, write media, or qualify the generated image for installation.
"""
from __future__ import annotations

import argparse
import json
import re
from pathlib import Path

PIN = "cbe253a43f46cf551cc9a6c79a84015bde3686cf"
FIXTURE = Path(__file__).resolve().parents[1] / "tests/fixtures/m1-rg34xx-toc1-provenance.json"


def align512(value: int) -> int:
    return (value + 511) & ~511


def main() -> int:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--baseos-root", type=Path, required=True)
    args = parser.parse_args()
    root = args.baseos_root.resolve()
    fixture = json.loads(FIXTURE.read_text())
    assert fixture["source_commit"] == PIN
    head = __import__("subprocess").run(
        ["git", "-C", str(root), "rev-parse", "HEAD"],
        check=True, capture_output=True, text=True).stdout.strip()
    if head != PIN:
        raise SystemExit(f"FAIL BaseOS pin mismatch: expected {PIN}, got {head}")

    native_build = (root / "experiments/h700-boot-speed/native/build.py").read_text()
    spl_build = (root / "experiments/h700-boot-speed/spl/build-early-mmc.py").read_text()
    native_boot = (root / "experiments/h700-boot-speed/spl/native-boot.c").read_text()

    # Verify the pinned builder extracts the four TOC1 items and packs only the
    # three vendor payloads plus the newly built loader into runtime firmware.bin.
    for token in (
        'assert result.keys() == {"u-boot", "monitor", "dtbo", "dtb"}',
        '("monitor", 0x48000000, toc["monitor"])',
        '("dtbo", 0x4a100000, toc["dtbo"])',
        '("dtb", 0x4a200000, toc["dtb"])',
        '("loader", 0x4a000000, bytes(blob))',
        'firmware.extend(payload)',
        'firmware.extend(bytes(-len(firmware) % 512))',
        '(output / "firmware.bin").write_bytes(firmware)',
        'f"\\n#define BASEOS_FIRMWARE_BYTES {len(firmware)}u\\n"',
        'BASEOS_FIRMWARE_FNV 0x{fnv(firmware):08x}u',
    ):
        if token not in native_build:
            raise SystemExit(f"FAIL pinned native builder contract missing: {token}")

    # The SPL build binds p4 + 40 MiB and exports the generated byte/FNV values.
    if "native_manifest['boot_partition_lba'] + 40 * 2048" not in spl_build:
        raise SystemExit("FAIL SPL builder no longer binds firmware to boot p4 + 40 MiB")
    if "BASEOS_FIRMWARE_BYTES" not in native_build or "BASEOS_FIRMWARE_FNV" not in native_build:
        raise SystemExit("FAIL native builder does not emit generated firmware length/fingerprint")
    if 'native_header = (native_loader / "native-generated.h").read_bytes()' not in spl_build:
        raise SystemExit("FAIL SPL builder no longer imports the native generated header")
    if '(arch / "native-generated.h").write_text(header)' not in spl_build:
        raise SystemExit("FAIL SPL builder no longer writes the combined generated header")

    # The consumer reads exactly the generated stream, validates its FNV, bounds
    # each extent, then copies to the generated destinations.
    for token in (
        "read_polled(card, BASEOS_FIRMWARE_SECTOR, BASEOS_FIRMWARE_BYTES / 512, package)",
        "fnv(package, BASEOS_FIRMWARE_BYTES) != BASEOS_FIRMWARE_FNV",
        "item->offset > BASEOS_FIRMWARE_BYTES",
        "item->bytes > BASEOS_FIRMWARE_BYTES - item->offset",
        "memcpy((void *)(ulong)item->destination, package + item->offset, item->bytes)",
    ):
        if token not in native_boot:
            raise SystemExit(f"FAIL pinned native consumer contract missing: {token}")

    items = fixture["items"]
    assert set(items) == {"u-boot", "monitor", "dtbo", "dtb"}
    assert fixture["toc1_package_bytes"] == 1_310_720
    assert re.fullmatch(r"[0-9a-f]{64}", fixture["toc1_package_sha256"])
    cursor = 0
    computed = []
    for name, destination in (
        ("monitor", "0x48000000"),
        ("dtbo", "0x4a100000"),
        ("dtb", "0x4a200000"),
        ("loader", "0x4a000000"),
    ):
        payload = fixture["linkslot_loader_bytes"] if name == "loader" else items[name]["bytes"]
        padded = align512(payload)
        computed.append((name, cursor, payload, padded, destination))
        cursor += padded

    expected = fixture["expected_firmware"]
    if cursor != expected["bytes"] or cursor != 0x46200 or cursor // 512 != 561:
        raise SystemExit(f"FAIL runtime firmware size mismatch: computed {cursor:#x}")
    for actual, declared in zip(computed, expected["regions"], strict=True):
        name, offset, payload, padded, destination = actual
        if (name, offset, payload, padded, destination) != (
            declared["name"], declared["offset"], declared["component_bytes"],
            declared["padded_bytes"], declared["destination"]
        ):
            raise SystemExit(f"FAIL extent mismatch for {name}: {actual!r} != {declared!r}")

    # Confirm that the package's component sizes match the captured TOC1 item directory.
    assert items["monitor"]["bytes"] == 0x1A2D0
    assert items["dtbo"]["bytes"] == 0x920
    assert items["dtb"]["bytes"] == 0x23400
    assert items["dtb"]["fdt_totalsize"] == 139822
    assert 0x1ae00 + items["dtb"]["fdt_totalsize"] == 0x3d02e
    assert fixture["linkslot_loader_bytes"] == 0x8000
    print("PASS captured TOC1 source item sizes/hashes pinned")
    print("PASS pinned BaseOS builder TOC1 -> firmware.bin packing contract")
    print("PASS p4+40MiB generated firmware length/FNV binding and native consumer")
    print("PASS 512-byte alignment: 0x1a400 + 0xa00 + 0x23400 + 0x8000 = 0x46200")
    print("PASS DTB FDT totalsize 139822; zero tail to 144384-byte copied component")
    print("LIMIT: source/layout proof only; firmware bytes/FNV must be generated and bound per build")
    print("LIMIT: no real card read, DRAM copy, SPL execution, or hardware qualification")
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
